CREATE OR REPLACE FUNCTION public.fn_validar_total_costo_insumo_detalle()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  v_suma NUMERIC(14,2);
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM public.costo co
      JOIN public.subcategoria_costo sc ON sc.idsubcategoria = co.idsubcategoria
      JOIN public.categoria_costo cc ON cc.idcategoria = sc.idcategoria
     WHERE co.idcosto = NEW.idcosto
       AND lower(btrim(cc.nombre)) = 'materia prima'
  ) THEN
    RETURN NEW;
  END IF;

  IF NOT EXISTS (
    SELECT 1
      FROM public.costo_insumo_detalle d
     WHERE d.idcosto = NEW.idcosto
  ) THEN
    RAISE EXCEPTION 'El costo de Materia Prima debe contener al menos un detalle.'
      USING ERRCODE = '23514';
  END IF;

  SELECT COALESCE(sum(d.subtotal), 0)
    INTO v_suma
    FROM public.costo_insumo_detalle d
   WHERE d.idcosto = NEW.idcosto;

  IF NEW.valor <> v_suma THEN
    RAISE EXCEPTION
      'El valor del costo (%) debe coincidir con la suma de sus detalles (%).',
      NEW.valor, v_suma
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$$;

