CREATE OR REPLACE FUNCTION inventario.fn_registrar_salida_con_destinos(
  p_usuario INTEGER,
  p_ip TEXT,
  p_producto INTEGER,
  p_finca INTEGER,
  p_usuario_retira INTEGER,
  p_cantidad NUMERIC,
  p_costo NUMERIC,
  p_total NUMERIC,
  p_saldo_cant NUMERIC,
  p_saldo_val NUMERIC,
  p_detalle TEXT,
  p_lote INTEGER,
  p_destinos_cultivo INTEGER[])
RETURNS INTEGER
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  v_id_kardex INTEGER;
  v_producto_finca INTEGER;
  v_total_destinos INTEGER;
  v_destinos_unicos INTEGER;
  v_idcultivo INTEGER;
BEGIN
  IF p_usuario_retira IS NULL
     OR p_destinos_cultivo IS NULL
     OR cardinality(p_destinos_cultivo) = 0
     OR array_position(p_destinos_cultivo, NULL) IS NOT NULL
     OR p_cantidad IS NULL OR p_cantidad <= 0
     OR p_costo IS NULL OR p_costo < 0
     OR p_total IS NULL OR p_total < 0 THEN
    RAISE EXCEPTION
      'La salida requiere receptor, cantidad válida y al menos un cultivo de destino.'
      USING ERRCODE = '22023';
  END IF;

  SELECT count(*), count(DISTINCT destinos.idcultivo)
    INTO v_total_destinos, v_destinos_unicos
    FROM unnest(p_destinos_cultivo) AS destinos(idcultivo);

  IF v_total_destinos <> v_destinos_unicos THEN
    RAISE EXCEPTION 'No se permiten cultivos de destino duplicados.'
      USING ERRCODE = '22023';
  END IF;

  SELECT p.id_finca
    INTO v_producto_finca
    FROM inventario.producto p
   WHERE p.id_producto = p_producto
     AND p.activo IS TRUE
   FOR KEY SHARE;

  IF NOT FOUND OR v_producto_finca <> p_finca THEN
    RAISE EXCEPTION
      'El producto debe estar activo y pertenecer a la finca indicada.'
      USING ERRCODE = '23514';
  END IF;

  PERFORM public.fn_auditoria_contexto(
    p_usuario, p_ip, NULL, NULL, 'INVENTARIO', p_detalle);

  INSERT INTO inventario.kardex (
    id_producto, id_finca, id_usuario, id_usuario_retira, tipo, cantidad,
    costo_unitario, total, saldo_cantidad, saldo_valor, detalle, id_lote
  )
  VALUES (
    p_producto, p_finca, p_usuario, p_usuario_retira, 'SALIDA', p_cantidad,
    p_costo, p_total, p_saldo_cant, p_saldo_val, p_detalle, p_lote
  )
  RETURNING id_kardex INTO v_id_kardex;

  FOREACH v_idcultivo IN ARRAY p_destinos_cultivo LOOP
    INSERT INTO inventario.kardex_destino_cultivo (id_kardex, idcultivo)
    VALUES (v_id_kardex, v_idcultivo);
  END LOOP;

  RETURN v_id_kardex;
END
$$;

REVOKE ALL ON FUNCTION inventario.fn_registrar_salida_con_destinos(
  INTEGER, TEXT, INTEGER, INTEGER, INTEGER, NUMERIC, NUMERIC, NUMERIC,
  NUMERIC, NUMERIC, TEXT, INTEGER, INTEGER[]
) FROM PUBLIC;

CREATE OR REPLACE FUNCTION public.fn_validar_costo_insumo_detalle()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  v_idfinca INTEGER;
  v_idcultivo INTEGER;
  v_categoria TEXT;
  v_finca_salida INTEGER;
  v_tipo_salida TEXT;
  v_cantidad_salida NUMERIC;
  v_costo_envase NUMERIC;
  v_contenido NUMERIC;
  v_unidad TEXT;
  v_cantidad_asociada NUMERIC;
  v_disponible NUMERIC;
BEGIN
  IF current_setting('app.materia_prima_detallada', true) IS DISTINCT FROM '1' THEN
    RAISE EXCEPTION
      'Los detalles de Materia Prima deben registrarse desde la operación transaccional de Costos.'
      USING ERRCODE = '23514';
  END IF;

  SELECT co.idfinca, co.idcultivo, lower(btrim(cc.nombre))
    INTO v_idfinca, v_idcultivo, v_categoria
    FROM public.costo co
    JOIN public.subcategoria_costo sc ON sc.idsubcategoria = co.idsubcategoria
    JOIN public.categoria_costo cc ON cc.idcategoria = sc.idcategoria
   WHERE co.idcosto = NEW.idcosto
   FOR KEY SHARE OF co;

  IF NOT FOUND OR v_categoria <> 'materia prima' OR v_idcultivo IS NULL THEN
    RAISE EXCEPTION
      'El detalle debe pertenecer a un costo de Materia Prima asociado a un cultivo.'
      USING ERRCODE = '23514';
  END IF;

  SELECT k.id_finca, k.tipo, k.cantidad, k.costo_unitario,
         pp.contenido_por_envase, pp.unidad_contenido
    INTO v_finca_salida, v_tipo_salida, v_cantidad_salida, v_costo_envase,
         v_contenido, v_unidad
    FROM inventario.kardex k
    JOIN inventario.presentacion_producto pp ON pp.id_producto = k.id_producto
   WHERE k.id_kardex = NEW.id_kardex
   FOR UPDATE OF k;

  IF NOT FOUND OR v_tipo_salida <> 'SALIDA' OR v_finca_salida <> v_idfinca THEN
    RAISE EXCEPTION
      'El detalle debe referenciar una salida de Kardex de la misma finca.'
      USING ERRCODE = '23514';
  END IF;

  IF NOT EXISTS (
    SELECT 1
      FROM inventario.kardex_destino_cultivo kd
     WHERE kd.id_kardex = NEW.id_kardex
       AND kd.idcultivo = v_idcultivo
  ) THEN
    RAISE EXCEPTION
      'La salida de Kardex no está destinada al cultivo del costo.'
      USING ERRCODE = '23514';
  END IF;

  IF NEW.cantidad_utilizada IS NULL OR NEW.cantidad_utilizada <= 0 THEN
    RAISE EXCEPTION 'La cantidad utilizada debe ser mayor que cero.'
      USING ERRCODE = '22023';
  END IF;

  SELECT COALESCE(sum(d.cantidad_utilizada), 0)
    INTO v_cantidad_asociada
    FROM public.costo_insumo_detalle d
   WHERE d.id_kardex = NEW.id_kardex
     AND d.idcosto_insumo_detalle IS DISTINCT FROM NEW.idcosto_insumo_detalle;

  v_disponible := (v_cantidad_salida * v_contenido) - v_cantidad_asociada;
  IF v_disponible < 0 OR NEW.cantidad_utilizada > v_disponible THEN
    RAISE EXCEPTION
      'La cantidad supera el saldo pendiente de la salida %. Disponible: % %.',
      NEW.id_kardex, GREATEST(v_disponible, 0), v_unidad
      USING ERRCODE = '23514';
  END IF;

  NEW.unidad_medida := v_unidad;
  NEW.costo_unitario_aplicado := v_costo_envase / v_contenido;
  NEW.subtotal := round(NEW.cantidad_utilizada * NEW.costo_unitario_aplicado, 2);
  RETURN NEW;
END
$$;

CREATE TRIGGER trg_validar_costo_insumo_detalle
  BEFORE INSERT OR UPDATE ON public.costo_insumo_detalle
  FOR EACH ROW EXECUTE FUNCTION public.fn_validar_costo_insumo_detalle();

