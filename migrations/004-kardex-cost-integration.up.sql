  'Cultivos habilitados como destino de una salida; no distribuye cantidades.';

CREATE TABLE public.costo_insumo_detalle (
  idcosto_insumo_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idcosto INTEGER NOT NULL
    REFERENCES public.costo(idcosto) ON DELETE RESTRICT,
  id_kardex INTEGER NOT NULL
    REFERENCES inventario.kardex(id_kardex) ON DELETE RESTRICT,
  cantidad_utilizada NUMERIC(18,6) NOT NULL CHECK (cantidad_utilizada > 0),
  unidad_medida VARCHAR(20) NOT NULL CHECK (btrim(unidad_medida) <> ''),
  costo_unitario_aplicado NUMERIC(18,6) NOT NULL
    CHECK (costo_unitario_aplicado >= 0),
  subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
  CONSTRAINT uq_costo_insumo_detalle_salida UNIQUE (idcosto, id_kardex)
);

CREATE INDEX ix_costo_insumo_detalle_kardex
  ON public.costo_insumo_detalle (id_kardex);

COMMENT ON TABLE public.costo_insumo_detalle IS
  'Consumos de salidas de Kardex asociados a costos. Las devoluciones no se descuentan mientras no exista una relación explícita con su salida original.';

CREATE OR REPLACE FUNCTION inventario.fn_validar_kardex_destino_cultivo()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  v_idfinca INTEGER;
  v_tipo TEXT;
  v_finca_cultivo INTEGER;
  v_estado_cultivo INTEGER;
  v_estado_registro SMALLINT;
BEGIN
  SELECT k.id_finca, k.tipo
    INTO v_idfinca, v_tipo
    FROM inventario.kardex k
   WHERE k.id_kardex = NEW.id_kardex
   FOR KEY SHARE;

  IF NOT FOUND OR v_tipo <> 'SALIDA' THEN
    RAISE EXCEPTION
      'Un destino de cultivo solo puede asociarse a una salida existente de Kardex.'
      USING ERRCODE = '23514';
  END IF;

  SELECT c.idfinca, c.idestadocultivo, c.estado_registro
    INTO v_finca_cultivo, v_estado_cultivo, v_estado_registro
    FROM public.cultivo c
   WHERE c.idcultivo = NEW.idcultivo
   FOR KEY SHARE;

  IF NOT FOUND
     OR v_finca_cultivo <> v_idfinca
     OR v_estado_cultivo <> 1
     OR v_estado_registro <> 1 THEN
    RAISE EXCEPTION
      'El cultivo de destino debe estar activo, En proceso y pertenecer a la finca de la salida.'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END
$$;

CREATE TRIGGER trg_validar_kardex_destino_cultivo
  BEFORE INSERT OR UPDATE ON inventario.kardex_destino_cultivo
  FOR EACH ROW EXECUTE FUNCTION inventario.fn_validar_kardex_destino_cultivo();

CREATE OR REPLACE FUNCTION inventario.fn_proteger_destino_cultivo_con_consumo()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  PERFORM 1
    FROM inventario.kardex k
   WHERE k.id_kardex = OLD.id_kardex
   FOR UPDATE;

  IF EXISTS (
    SELECT 1
      FROM public.costo_insumo_detalle d
      JOIN public.costo co ON co.idcosto = d.idcosto
     WHERE d.id_kardex = OLD.id_kardex
       AND co.idcultivo = OLD.idcultivo
  ) THEN
    RAISE EXCEPTION
      'No se puede cambiar o eliminar un destino de Kardex que ya tiene consumos asociados.'
      USING ERRCODE = '23514';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER trg_proteger_destino_cultivo_con_consumo
  BEFORE UPDATE OR DELETE ON inventario.kardex_destino_cultivo
  FOR EACH ROW EXECUTE FUNCTION inventario.fn_proteger_destino_cultivo_con_consumo();

