  id_kardex INTEGER NOT NULL
    REFERENCES inventario.kardex(id_kardex) ON DELETE RESTRICT,
  idcultivo INTEGER NOT NULL
    REFERENCES public.cultivo(idcultivo) ON DELETE RESTRICT,
  CONSTRAINT uq_kardex_destino_cultivo UNIQUE (id_kardex, idcultivo)
